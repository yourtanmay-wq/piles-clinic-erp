package com.tkbiswas.pilesclinic.native

import android.print.PrintAttributes

/**
 * 🖨️🔒 V1351 (১১.০৯.২০২৬, TK-রিপোর্ট ছবিসহ — "প্রিন্ট আউট হওয়ার পরে
 * উজ্জ্বলতা নেই, শুধু এই কাগজ নয় — প্রেসক্রিপশন/মেডিসিন স্লিপ/ডায়েট চার্ট
 * সহ অ্যাপ থেকে যা প্রিন্ট হয় সবই এরকম, গভীরে যাচাই করে সততার সাথে
 * ঠিক করে দিন") — গভীরে যাচাই করে পাওয়া:
 *
 *  ① রঙের CSS (`print-color-adjust`) আগেই ঠিক করা আছে (V1341) — তাই এটা
 *     রঙ চেপে যাওয়ার সমস্যা নয়।
 *  ② প্রকল্পের **একটাও** প্রিন্ট-জব printer-কে স্পষ্ট করে রেজোলিউশন/রঙিন
 *     মোড **চাইতই না** — খালি `PrintAttributes.Builder().build()` পাঠানো
 *     হত, তাই printer/driver নিজের ডিফল্ট বেছে নিত (কিছু ফোন/প্রিন্টারে
 *     সেটা কম-রেজোলিউশন বা ধূসর/কালো-সাদা ডিফল্ট হতে পারে — নতুন প্রিন্টার
 *     হলেও)। এটাই সব প্রিন্টে **একইভাবে** হালকা/অস্পষ্ট আসার সবচেয়ে
 *     সম্ভাব্য কারণ, কারণ এই একটামাত্র জায়গায় (PrintManager-কে ডাকার
 *     মুহূর্তে) সবগুলো প্রিন্ট-টেমপ্লেট একই পথ দিয়ে যায়।
 *
 * ⛔ পাতার মাপ/মার্জিন এখানে ছোঁয়া হয়নি — যে কল-সাইট আগে যা চেয়েছিল
 *    (A4/মার্জিন-ছাড়া/কোনোটাই না) তা অক্ষত থাকে; শুধু রেজোলিউশন ও
 *    রঙিন-মোড স্পষ্টভাবে যোগ হলো। প্রিন্টার/ড্রাইভার এই অনুরোধ সমর্থন
 *    না করলেও Android নিজে থেকেই কাছাকাছি যা সমর্থন করে সেটা বেছে নেয় —
 *    কোনো প্রিন্ট ব্যর্থ হবে না।
 */
object PrintQuality {
    fun builder(): PrintAttributes.Builder =
        PrintAttributes.Builder()
            .setResolution(PrintAttributes.Resolution("high_quality", "High Quality", 300, 300))
            .setColorMode(PrintAttributes.COLOR_MODE_COLOR)
}
