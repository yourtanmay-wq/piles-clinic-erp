package com.tkbiswas.pilesclinic.native

import android.view.ViewGroup

/**
 * 🖥️🔒 V509 (২১.০৮.২০২৬, TK-রিপোর্ট) — **পর্দার ঝিলিক বন্ধ করা।**
 *
 * ─── TK-এর অভিযোগ ─────────────────────────────────────────────────────────
 * > *"অ্যাপসের মধ্যে ঢুকে অনেক জায়গাতে স্ক্রিন কম্পন দিচ্ছে।"*
 *
 * ─── যাচাই করে যা পাওয়া গেছে (অনুমান নয়) ──────────────────────────────────
 * অ্যাপ **ফোন কাঁপায় না** — কম্পনের কোড মাত্র দুই জায়গায় (ট্রিপল-ট্যাপ ও
 * নোটিফিকেশন), ঝাঁকুনির কোড কোথাও নেই।
 *
 * আসল কারণ **"দুবার আঁকা"**। অনেক পর্দা এই প্রমাণিত ধাঁচে চলে —
 *   ১) ফোনে জমানো (cache) তথ্য দিয়ে **সঙ্গে সঙ্গে** পর্দা আঁকা হয়, আর
 *   ২) ক্লাউড থেকে উত্তর এলে **পুরো পর্দা মুছে আবার** আঁকা হয়।
 * বেশিরভাগ সময় দুটো তথ্য **হুবহু এক**, তবু দ্বিতীয়বার মুছে-আঁকা হয় —
 * চোখে সেটাই এক ঝলক **ঝিলিক** মনে হয়।
 *
 * ─── এই পাহারা কী করে ─────────────────────────────────────────────────────
 * প্রতিটা ঘরের (container) জন্য মনে রাখে **শেষবার কী আঁকা হয়েছিল**।
 * নতুন তথ্য হুবহু এক হলে বলে দেয় "আর আঁকার দরকার নেই"।
 *
 * ─── ⛔ কেন এতে কিছু ভাঙতে পারে না ────────────────────────────────────────
 *  • তথ্য **এক চুল আলাদা হলেই** আগের মতোই পুরো আঁকা হয় — কিছু চাপা পড়ে না।
 *  • ঘরটা **ফাঁকা থাকলে** (childCount == 0) কখনো এড়ানো হয় না — অর্থাৎ
 *    "কিছুই দেখাল না" এমন হতে পারে না।
 *  • `WeakHashMap` — পর্দা বন্ধ হলে হিসাবটা নিজে থেকেই ছেড়ে যায়, মেমরি ধরে
 *    রাখে না।
 *  • কোনো তথ্য · হিসাব · টাকা · ডিজাইন · ক্লাউড-কল কিছুই ছোঁয়া হয় না —
 *    শুধু **অকারণে আবার আঁকা** বন্ধ হয়। ক্লাউড-কল আগের মতোই হয়, তাই
 *    নতুন তথ্য এলে সঙ্গে সঙ্গেই দেখা যায়।
 *
 * ⚠️ সৎ সীমা: যদি কোনো পর্দা তার ঘরটা **বাইরে থেকে** বদলে ফেলে (এই ঘরে
 *    হাত না দিয়ে), তবু ফাঁকা-যাচাইয়ের কারণে কখনো খালি পর্দা থাকবে না।
 *    সন্দেহ হলে ওই পর্দায় এই পাহারা বসানোই হয়নি।
 */
object RedrawGuard {

    /** ঘর → শেষবার আঁকা তথ্যের চিহ্ন। WeakHashMap বলে মেমরি আটকায় না। */
    private val lastDrawn = java.util.WeakHashMap<ViewGroup, String>()

    /**
     * @return `true` = **আঁকার দরকার নেই** (হুবহু একই জিনিস আগে থেকেই দেখা যাচ্ছে)।
     *         `false` = আগের মতোই পুরো আঁকুন।
     *
     * ডাকার নিয়ম — ঠিক আঁকা শুরুর আগে:
     * ```
     * if (RedrawGuard.alreadyShowing(box, rows.toString())) return
     * box.removeAllViews()
     * …আগের মতো আঁকা…
     * ```
     */
    fun alreadyShowing(target: ViewGroup?, signature: String?): Boolean {
        if (target == null) return false
        return try {
            val sig = signature ?: ""
            // ঘর ফাঁকা হলে কখনো এড়ানো নয় — নইলে খালি পর্দা থেকে যেত।
            if (target.childCount == 0) {
                lastDrawn[target] = sig
                false
            } else if (lastDrawn[target] == sig) {
                true                       // হুবহু এক — ঝিলিকের দরকার নেই
            } else {
                lastDrawn[target] = sig
                false
            }
        } catch (_: Throwable) {
            false                          // সন্দেহ হলে আগের আচরণ (আঁকা হোক)
        }
    }

    /** কোনো ঘরের হিসাব ভুলে যাওয়া — পরের বার নিশ্চিতভাবে আবার আঁকবে। */
    fun forget(target: ViewGroup?) {
        try { if (target != null) lastDrawn.remove(target) } catch (_: Throwable) { }
    }
}
