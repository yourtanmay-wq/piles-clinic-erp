package com.tkbiswas.pilesclinic.native

import org.json.JSONObject

/**
 * 🔴🔒 V715 (২৬.০৮.২০২৬, TK-নির্দেশ — Supabase Egress-এর আসল কারণ সারানো)
 *
 * ─── কেন এই ফাইলটা লাগল (মাপা তথ্য, আন্দাজ নয়) ────────────────────────────
 * Supabase-এর নিজের লগ থেকে মেপে পাওয়া গেছে: গত ২৪ ঘণ্টায়
 * `GET /rest/v1/followups` চলেছে **২০,৩১২ বার**, আর তার প্রায় **১১,৭০০ বার**
 * এসেছে একটামাত্র জায়গা থেকে — **একটা আটকে থাকা পেমেন্ট**
 * (`piles_clinic_payment_pending`)।
 *
 * `flushPending()` চলে **প্রতিবার যেকোনো পর্দা খোলার সময়** (`BottomNav.wire()`)
 * আর **প্রতি ১৫ মিনিটে** (`SyncWorker`)। সারিটা যদি এমন কারণে আটকে থাকে যেটা
 * নিজে থেকে সারে না (এখানে: ডেটাবেসের `tk_terminal_no_return` ট্রিগার নতুন
 * সারিটা চুপচাপ ফেলে দিচ্ছিল), তাহলে সেই একই ভারী কাজটা **দিনে ~৪,০০০ বার**
 * চলে — অথচ ফল প্রতিবার একই।
 *
 * ─── এই ফাইল কী করে ───────────────────────────────────────────────────────
 * পরপর ব্যর্থ হতে থাকা সারির চেষ্টার **ফাঁক বাড়িয়ে দেয়**:
 *
 *      ব্যর্থ ১–২ বার → **সঙ্গে সঙ্গে** আবার (আগের আচরণ হুবহু — দুর্বল নেট
 *                        বা সাময়িক গোলমাল এতে একটুও দেরি করে না)
 *      ব্যর্থ ৩ বার   → ১ মিনিট পরে
 *      ব্যর্থ ৪ বার   → ৫ মিনিট পরে
 *      ব্যর্থ ৫ বার   → ১৫ মিনিট পরে
 *      ব্যর্থ ৬+ বার  → ১ ঘণ্টা পরে (এর বেশি নয়)
 *
 * ─── 🔒 নিরাপত্তা (প্রতিটা ইচ্ছে করে বসানো) ────────────────────────────────
 *  • **কোনো সারি কখনো ফেলে দেওয়া হয় না।** এই ফাইল শুধু "এখন চেষ্টা করব কি
 *    না" বলে — কোনো কাজ মুছতে বা বাতিল করতে পারে না। তথ্য হারানোর পথ নেই।
 *  • **মালিক/স্টাফ নিজে "Send" চাপলে অপেক্ষা মানা হয় না** (`force = true`) —
 *    হাতে চাপলে সঙ্গে সঙ্গেই চেষ্টা হয়, ঠিক আগের মতোই।
 *  • **প্রথম দু'বার কোনো দেরি নেই** — অর্থাৎ সত্যিকারের নেট-সমস্যায় আচরণ
 *    এক অক্ষরও বদলায়নি। দেরি শুরু হয় শুধু তখনই, যখন একই সারি বারবার
 *    (৩ বার+) একই ভাবে ব্যর্থ হচ্ছে।
 *  • **সফল হলে হিসাব মুছে যায়** — সারিটা তালিকা থেকেই উঠে যায়, তাই পরের
 *    কাজ কখনো আগের ব্যর্থতার শাস্তি পায় না।
 *  • **ফোনের ঘড়ি পিছিয়ে/এগিয়ে থাকলেও আটকাবে না** — অপেক্ষার সময় যদি
 *    ১ ঘণ্টার বেশি ভবিষ্যতে দেখায় (মানে ঘড়ি নড়েছে), তখনই চেষ্টা করা হয়।
 *  • **গোলমাল হলে চুপচাপ সরে দাঁড়ায়** — যেকোনো ব্যতিক্রমে "চেষ্টা করো" বলে,
 *    অর্থাৎ সবচেয়ে খারাপ অবস্থাতেও আচরণ আগের মতোই।
 *
 * ⛔ টাকার অঙ্ক · হিসাব · ডিজাইন · কোন সারি যায় · কী পাঠানো হয় — কিছুই
 *    ছোঁয়া হয়নি। শুধু **কখন আবার চেষ্টা হবে** সেটুকুই।
 */
object PendingRetryBackoff {

    /** সারির ভিতরে এই দুটো বাড়তি ঘর রাখা হয় — অন্য কোনো কোড এগুলো পড়ে না। */
    private const val K_FAILS = "rkFailCount"
    private const val K_NEXT  = "rkNextTryAt"

    /** এর আগে কোনো দেরি নেই — সাময়িক নেট-সমস্যায় আচরণ হুবহু আগের মতো। */
    private const val FREE_TRIES = 2

    /* 🔵🔒 V717 (নিজে গভীরে যাচাই করে ধরা) — **সর্বোচ্চ অপেক্ষা ১ ঘণ্টা থেকে
       কমিয়ে ১৫ মিনিট।**

       কেন: ফোন অনেকক্ষণ নেটের বাইরে থাকলে (সন্ধ্যায় টাকা নেওয়া হলো, লাইন নেই)
       একটা **সত্যিকারের** সারিও পরপর ব্যর্থ হয়ে ১ ঘণ্টার ঘরে পৌঁছে যেতে পারত —
       তারপর নেট ফিরলেও সেটা এক ঘণ্টা পর্যন্ত বসে থাকত। আগে এমন হত না।
       ⇒ সেটা "ভাল কাজ খারাপ হওয়া"। তাই সর্বোচ্চ ১৫ মিনিট।
       ⇒ আটকে থাকা সারির খরচ তবুও দিনে ~৪,০০০ → ~১০০ বার (৯৭%+ কম)। */
    private const val MAX_WAIT_MS = 15L * 60L * 1000L   // ১৫ মিনিট

    private fun waitFor(fails: Int): Long = when {
        fails <= FREE_TRIES -> 0L
        fails == 3          -> 60L * 1000L
        fails == 4          -> 5L * 60L * 1000L
        else                -> MAX_WAIT_MS
    }

    /**
     * এখন এই সারিটা চেষ্টা করা হবে কি না।
     * @param force মালিক/স্টাফ নিজে "Send" চেপেছেন — তখন অপেক্ষা মানা হয় না।
     */
    fun shouldTry(entry: JSONObject?, force: Boolean): Boolean {
        if (entry == null) return true
        if (force) return true
        return try {
            val next = entry.optLong(K_NEXT, 0L)
            if (next <= 0L) return true
            val now = System.currentTimeMillis()
            if (next <= now) return true
            // ঘড়ি নড়ে গেলে যেন চিরকাল আটকে না থাকে।
            if (next - now > MAX_WAIT_MS) return true
            false
        } catch (_: Throwable) { true }
    }

    /** এই সারিটা আবার ব্যর্থ হয়েছে — পরের চেষ্টার সময় ঠিক করে দেওয়া। */
    fun noteFailure(entry: JSONObject?) {
        if (entry == null) return
        try {
            val fails = entry.optInt(K_FAILS, 0) + 1
            entry.put(K_FAILS, fails)
            val wait = waitFor(fails)
            if (wait > 0L) entry.put(K_NEXT, System.currentTimeMillis() + wait)
            else entry.remove(K_NEXT)
        } catch (_: Throwable) { }
    }

    /**
     * 🔵🔒 V717 — **নেট ভালো আছে, এটা প্রমাণ হলেই সবার অপেক্ষা মুছে যায়।**
     *
     * একই দফায় অন্য কোনো সারি সফল হওয়া মানে লাইন ঠিক আছে — তখন বাকিদের
     * অপেক্ষা করানোর আর কোনো কারণ নেই (তাদের ব্যর্থতা নেটের দোষ ছিল)।
     * ⇒ নেট ফেরার সঙ্গে সঙ্গেই সত্যিকারের সারিগুলো আবার চেষ্টা পায়।
     * ⛔ শুধু অপেক্ষার হিসাব মোছে — কোনো সারি/তথ্য ছোঁয়া হয় না।
     */
    fun clearWait(entry: JSONObject?) {
        if (entry == null) return
        try { entry.remove(K_NEXT); entry.remove(K_FAILS) } catch (_: Throwable) { }
    }

    /**
     * শুধু দেখানোর জন্য — এই সারিটা কতবার ব্যর্থ হয়েছে।
     * (V706-এর পেন্ডিং তালিকায় ভবিষ্যতে কাজে লাগতে পারে।)
     */
    fun failCount(entry: JSONObject?): Int = try { entry?.optInt(K_FAILS, 0) ?: 0 } catch (_: Throwable) { 0 }
}
