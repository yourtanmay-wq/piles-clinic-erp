create table if not exists public.dialer_calls (
    "id" text primary key,
    "staffMobile" text,
    "staffName" text,
    "branch" text,
    "dialedNumber" text,
    "calledAt" text
);

-- দ্রুত খোঁজার জন্য (একজন স্টাফের আজকের তালিকা বার করার সময় প্রতিবার
-- পুরো টেবিল স্ক্যান না করে দ্রুত বার করা যায়)।
create index if not exists idx_dialer_calls_staff_date
    on public.dialer_calls ("staffMobile", "calledAt");

