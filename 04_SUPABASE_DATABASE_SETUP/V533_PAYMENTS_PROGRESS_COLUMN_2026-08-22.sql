-- V533 (২২.০৮.২০২৬) — payments টেবিলে চিকিৎসার নোটের নিজস্ব ঘর
--
-- TK-এর সিদ্ধান্ত: "নোট আলাদা ঘরে রাখব।"
--
-- কেন দরকার:
--   Chamber-এ চিকিৎসার নোট ("DRESSING করা হল") লিখলে অ্যাপ সেটা ওইদিনের
--   প্রতিটা payment সারির `remarks` ঘরে বসিয়ে দিত। ফলে স্টাফের নিজের হাতে
--   লেখা পেমেন্ট-Remark, Medicine-এর Remark, এমনকি **Refund-এর কারণ** —
--   সব মুছে গিয়ে চিকিৎসার নোট বসে যেত।
--
-- এই ফাইলটা কী করে:
--   শুধু **একটা নতুন ফাঁকা ঘর** যোগ করে। আর কিচ্ছু না।
--
-- ⛔ কোনো পুরোনো তথ্য মোছে না, বদলায় না, সরায় না।
-- ⛔ কোনো RLS / নিরাপত্তার নিয়ম ছোঁয় না।
-- ⛔ ঘরটা ফাঁকা থাকে — তাই পুরোনো প্রতিটা সারিতে অ্যাপ আগের মতোই
--    `remarks`-ই পড়ে (কোডে: `progress` ফাঁকা হলে `remarks`)। একটা পুরোনো
--    নোটও হারায় না।
-- ⛔ দু'বার চালালেও কিছু হয় না (`if not exists`)।
--
-- 🔴 এটা **V533 বিল্ড করার আগে** একবার চালাতে হবে। না চালালে নতুন নোট
--    সার্ভারে বসতে পারবে না (অ্যাপ সেগুলো নিজের কিউ-তে জমিয়ে রাখবে,
--    হারাবে না — কিন্তু Report Card-এ দেখা যাবে না)।
-- ═══════════════════════════════════════════════════════════════════════

alter table public.payments
  add column if not exists progress text;

