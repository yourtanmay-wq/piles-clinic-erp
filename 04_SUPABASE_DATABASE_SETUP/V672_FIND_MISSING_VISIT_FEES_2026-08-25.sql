-- V672 (নির্ণায়ক রিপোর্ট) — Visit Fee হারিয়ে যাওয়া রোগীদের তালিকা
-- =====================================================================
-- B455 (05.08.2026-এ যোগ হওয়া) থেকে আজ (25.08.2026) পর্যন্ত — এই
-- সময়ের ভিতরে যেসব রোগী রেজিস্টার হয়েছেন কিন্তু তাদের কোনো
-- "visit_fee" পেমেন্ট-সারি নেই, তাদের তালিকা।
--
-- ⛔ এটা শুধু **দেখার/যাচাইয়ের** জন্য — কিছুই বদলায় না, কিছু মোছে না।
-- ⛔ Android থেকে করা রেজিস্ট্রেশনে এই বাগ ছিল না (আলাদাভাবে যাচাই
--    করা হয়েছে) — তাই তালিকায় Android থেকে করা কিছু রোগীও দেখা যেতে
--    পারে যাদের আসলে সমস্যা নেই (যেমন কেউ প্রথমেই বিল ০ টাকায়
--    রেজিস্টার হয়ে থাকলে, বা অন্য বৈধ কারণে ফি নেওয়া হয়নি) —
--    প্রতিটা সারি TK নিজে চোখে দেখে বিচার করবেন, স্বয়ংক্রিয়ভাবে
--    কিছু ঠিক করা হচ্ছে না।
--
-- চালানোর নিয়ম: Supabase → SQL Editor → New query → পুরো ফাইল পেস্ট
-- → Run। ফলাফলের টেবিলটা Export/দেখে TK যাচাই করবেন।
-- =====================================================================

select
  p."patientId"   as "Patient ID",
  p.name          as "Name",
  p.mobile        as "Mobile",
  p.branch        as "Branch",
  p."registrationDate" as "Registration Date",
  p."createdAt"   as "Created At"
from public.patients p
where p."createdAt" >= '2026-08-05'
  and coalesce(p."registrationDate", p."createdAt") is not null
  and not exists (
    select 1 from public.payments x
    where x."patientId" = p.id and x."payType" = 'visit_fee'
  )
order by p."createdAt" asc;
