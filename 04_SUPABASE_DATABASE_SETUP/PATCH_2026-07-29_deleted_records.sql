create table if not exists public.deleted_records (
  "id"        text primary key,   -- টেবিলের নাম | সারির আইডি
  "tableName" text,
  "rowId"     text,
  "deletedBy" text,
  "deletedAt" text
);

alter table public.deleted_records disable row level security;

create index if not exists deleted_records_rowid_idx
  on public.deleted_records ("rowId");
