-- ওষুধ বিক্রির পুরনো সারিতে  mode = 'UPI'  →  'ONLINE'
-- ============================================================================
--
-- 🔴 কেন দরকার:
--    ফোনের অ্যাপ ওষুধ বিক্রির সারিতে সবসময় 'CASH' বা 'ONLINE' লেখে, আর পড়ার
--    সময়ও দেখে:  if (mode == "ONLINE") online else cash
--                 (MedicinePaymentActivity.kt:443, 610)
--    কিন্তু ওয়েব-অ্যাপ এতদিন 'UPI' লিখত। ফলে **ওয়েব থেকে নেওয়া অনলাইন
--    ওষুধ-বিক্রি ফোনে CASH-এ গোনা হচ্ছিল** — Cash বেশি, Online কম দেখাত।
--    V437-এ ওয়েবের লেখাটা ঠিক করা হয়েছে, কিন্তু **আগের সারিগুলো** এখনো 'UPI'।
--    এই SQL শুধু ওই পুরনো সারিগুলো ঠিক করে।
--
-- 🔧 ১৮.০৮.২০২৬ সংশোধন (TK-এর চালানোর সময় ধরা পড়েছে):
--    প্রথম বারে ভুল হয়েছিল — ERROR 42804 "COALESCE types text and integer
--    cannot be matched"। কারণ `deposit` ঘরটা ডেটাবেসে **লেখা (text)** ধরনের,
--    সংখ্যা নয়; তাই `COALESCE(deposit, 0)` চলেনি। এখন টাকার যোগফলটা নিরাপদে
--    বার করা হয় — যে সারিতে সত্যিই সংখ্যা আছে শুধু সেটাই যোগ হয়, বাকিগুলো ০।
--    ⛔ এতে **ধাপ ২-এর আসল কাজ একটুও বদলায়নি** (ওটাতে কোনো ভুল ছিল না)।
--
-- ⛔ নিরাপত্তা:
--    · শুধু  kind = 'medicinePayment'  সারিতে — রোগীর পেমেন্ট (payments টেবিল)
--      একেবারেই ছোঁয়া হয় না।
--    · শুধু  mode  ঘরটা — টাকা (bill/deposit/due) · তারিখ · নাম · কিছুই নয়।
--    · 'CASH' সারিতে হাত পড়ে না।
--    · বারবার চালালেও কিছু হয় না (দ্বিতীয়বার ০টা সারি বদলাবে) — নিরাপদ।
--
-- 👉 কীভাবে চালাবেন: Supabase → SQL Editor → নিচেরটা কপি-পেস্ট → Run
--    ধাপ ১ ও ৩ শুধু **দেখার** জন্য, কিছু বদলায় না।
-- ============================================================================


-- ────────────────────────────────────────────────────────────────────────
-- ধাপ ১ — আগে দেখে নিন: কতগুলো সারি বদলাবে?  (কিছুই বদলায় না)
-- ────────────────────────────────────────────────────────────────────────
SELECT
  COALESCE(branch, '(ব্রাঞ্চ নেই)') AS branch,
  COUNT(*)                          AS row_count,
  SUM(
    CASE WHEN deposit::text ~ '^\s*[0-9]+(\.[0-9]+)?\s*$'
         THEN deposit::text::numeric
         ELSE 0 END
  )                                 AS total_money
FROM public.products
WHERE kind = 'medicinePayment'
  AND UPPER(TRIM(COALESCE(mode::text, ''))) = 'UPI'
GROUP BY 1
ORDER BY 1;


-- ────────────────────────────────────────────────────────────────────────
-- ধাপ ২ — আসল কাজ:  UPI → ONLINE
-- ────────────────────────────────────────────────────────────────────────
UPDATE public.products
SET mode = 'ONLINE'
WHERE kind = 'medicinePayment'
  AND UPPER(TRIM(COALESCE(mode::text, ''))) = 'UPI';


-- ────────────────────────────────────────────────────────────────────────
-- ধাপ ৩ — মিলিয়ে দেখুন:  এখন যেন একটাও 'UPI' না থাকে
--          (upi_left অবশ্যই 0 হবে)
-- ────────────────────────────────────────────────────────────────────────
SELECT
  COUNT(*) FILTER (WHERE UPPER(TRIM(COALESCE(mode::text,''))) = 'UPI')    AS upi_left,
  COUNT(*) FILTER (WHERE UPPER(TRIM(COALESCE(mode::text,''))) = 'ONLINE') AS online_now,
  COUNT(*) FILTER (WHERE UPPER(TRIM(COALESCE(mode::text,''))) = 'CASH')   AS cash_now,
  COUNT(*)                                                                AS all_medicine_rows
FROM public.products
WHERE kind = 'medicinePayment';
