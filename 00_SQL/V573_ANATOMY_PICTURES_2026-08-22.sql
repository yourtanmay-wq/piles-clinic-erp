create table if not exists public.anatomy_pictures (
  "id" text primary key,            -- যোগ করা ছবি: pic_<সময়> · লুকানো: hide_<ছবির নাম>
  "picKey" text,                    -- অ্যাপের ছবির নাম (anat07) — লুকানোর সারিতে
  "label" text,                     -- ছবির নাম, ডাক্তার যা লিখবেন
  "photo" text,                     -- যোগ করা ছবিটা (ছোট করা JPEG, data URL)
  "hidden" text,                    -- "1" হলে তালিকায় দেখানো বন্ধ
  "sortOrder" text,                 -- কোনটা আগে দেখাবে
  "createdBy" text,
  "createdAt" text,
  "updatedAt" text
);

alter table public.anatomy_pictures disable row level security;

-- PostgREST-কে নতুন টেবিলটার কথা জানানো
notify pgrst, 'reload schema';

