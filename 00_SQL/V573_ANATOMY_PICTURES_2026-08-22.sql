-- V573 (২২.০৮.২০২৬) — রোগের ছবির তালিকায় **যোগ ও বিয়োগ**
--
-- TK-এর নির্দেশ: *"যেখানে সমস্ত ফটো আছে সেখানে যেন গ্যালারি থেকেও ফটো নেয়া
-- যায় অথবা ক্যামেরা থেকেও ফটো নিয়ে দেখানো যায় ... তাছাড়া এর আগে যে সমস্ত
-- ফটো আছে সেগুলো আমরা চাইলে যোগ এবং বিয়োগ যেন করতে পারি"*।
-- TK বেছেছেন: **সব ডিভাইসে এক** (ক্লাউডে), তাই এই ছোট টেবিলটা লাগছে।
--
-- এই টেবিলে কী থাকে:
--   • ডাক্তার নিজে যোগ করা ছবি — একটা সারি, ছবিটা `photo` ঘরে
--     (ছোট করা JPEG, ছবি-প্রতি আনুমানিক ৫০–৮০ KB)।
--   • অ্যাপের সাথে আসা যে ছবিগুলো TK তালিকা থেকে সরাতে চান — সেগুলোর
--     জন্য শুধু একটা `hidden = true` সারি (ছবিটা মোছা হয় না, শুধু
--     তালিকায় দেখানো বন্ধ)।
--
-- ⛔ পুরোনো কোনো টেবিল বা তথ্য ছোঁয়া হয়নি — এটা সম্পূর্ণ নতুন, আলাদা।
-- ⛔ পুরোনো চেক-আপে যে ছবির উপরে আঁকা হয়েছিল, সেটা তালিকা থেকে সরালেও
--    **ওই পুরোনো রেকর্ড আগের মতোই ঠিক দেখাবে** — সরানো মানে শুধু "নতুন
--    করে আর বাছা যাবে না"।
-- ⛔ দু'বার চালালেও কিছু হয় না (`if not exists`)।
-- ⛔ প্রজেক্টের বাকি টেবিলের মতোই একই নিরাপত্তার নিয়ম — নতুন কিছু নয়।
--
-- 📦 জায়গা: ৫০টা ছবি যোগ করলেও ~৪ MB — Supabase ফ্রি প্ল্যানে (৫০০ MB)
--    কোনো সমস্যা নেই। তালিকাটা অ্যাপ **দিনে একবারের মতো** টানে, তারপর
--    ফোনেই জমা রাখে — তাই বারবার ডেটা খরচ হয় না।
--
-- কীভাবে চালাবেন:
