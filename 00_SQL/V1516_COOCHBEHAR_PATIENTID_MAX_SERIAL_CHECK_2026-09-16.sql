-- কোচবিহার ব্রাঞ্চ -- ধাপ ১খ। শুধু SELECT, কিছু বদলায় না।
-- জলপাইগুড়িতে আগে patientId সংঘর্ষ হয়েছিল (একই তারিখে লাইভ অ্যাপে আগে
-- থেকেই রোগী থাকায়) -- সেই ভুল যেন আবার না হয়, তাই আগেভাগেই আমাদের
-- ১০৯ জনের ৭২টা তারিখের জন্য লাইভে কোন সর্বোচ্চ serial সংখ্যা ব্যবহৃত
-- আছে তা দেখে নেওয়া হচ্ছে।

select
  substring("patientId" from 5 for 8) as date_part,
  max(substring("patientId" from 14)::int) as max_serial_used,
  count(*) as total_on_date
from public.patients
where "patientId" ~ '^COB-\d{8}-\d+$'
  and substring("patientId" from 5 for 8) in (
    '01062025','01072025','02052025','02062025','02082025','03102025','03112025','04042025','04072025','04082025',
    '05022025','05052025','05072025','05112025','06052025','06062025','06102025','07022025','07032025','07042025',
    '07072025','07112025','08082025','08092025','09052025','09062025','10022025','10032025','10102025','11042025',
    '11072025','12092025','14022025','14032025','14042025','14072025','14112025','15092025','15122025','16052025',
    '16062025','16102025','17022025','17112025','18042025','18072025','19052025','19122025','20062025','21022025',
    '21042025','21112025','22022025','22082025','22122025','23052025','23062025','23082025','23102025','25032025',
    '25042025','25072025','26022025','26112025','26122025','28022025','28032025','28042025','28062025','30062025',
    '31032025','31102025'
  )
group by date_part
order by date_part;
